function ComboboxChip({
  className,
  children,
  showRemove = true,
  removeLabel = "선택 해제",
  ...props
}: ComboboxPrimitive.Chip.Props & {
  showRemove?: boolean
  /** 칩 지우기 버튼의 접근 가능한 이름. 칩 내용을 넣어 구분한다(예: "디자인 선택 해제"). */
  removeLabel?: string
}) {
  return (
    <ComboboxPrimitive.Chip
      data-slot="combobox-chip"
      className={cn(
        "flex h-6 w-fit items-center justify-center gap-1 rounded-full bg-accent px-2.5 text-xs font-medium whitespace-nowrap text-foreground has-disabled:pointer-events-none has-disabled:cursor-not-allowed has-disabled:bg-muted has-disabled:text-mute has-data-[slot=combobox-chip-remove]:pr-0",
        className
      )}
      {...props}
    >
      {children}
      {showRemove && (
        <ComboboxPrimitive.ChipRemove
          render={<Button variant="ghost" size="icon-xs" />}
          className="-ml-1 text-muted-foreground hover:text-foreground"
          data-slot="combobox-chip-remove"
          aria-label={removeLabel}
        >
          <XIcon className="pointer-events-none" aria-hidden="true" />
        </ComboboxPrimitive.ChipRemove>
      )}
    </ComboboxPrimitive.Chip>
  )
}

